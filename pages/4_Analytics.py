"""
Page E: Analytics & Aggregation Reports
ScamShield: AI-Powered Fake Job & Internship Detection System

Demonstrates core CSE494 syllabus topic: The MongoDB Aggregation Framework.
Uses Plotly charts and MongoDB pipelines ($group, $project, $sort) to analyze:
- Prediction distributions vs ground-truth dataset distributions
- Temporal prediction trends
- Model usage statistics
- End-user feedback metrics
"""

import streamlit as st
import config
from ui_utils import apply_custom_css, render_header, render_sidebar
from database.connection import get_db, check_connection
from database.operations import (
    get_predictions_class_distribution,
    get_predictions_daily_trend,
    get_model_usage_aggregation,
    get_feedback_breakdown,
    get_jobs_ground_truth_distribution,
)
from analytics.reports import (
    create_prediction_distribution_chart,
    create_daily_trends_chart,
    create_model_usage_chart,
    create_feedback_distribution_chart,
    create_ground_truth_distribution_chart,
    create_model_comparison_chart,
)
from ml.evaluate import load_metrics_json

st.set_page_config(
    page_title="Analytics & Reports | ScamShield",
    page_icon="📈",
    layout="wide",
)

apply_custom_css()
render_sidebar()

render_header(
    title="Analytics & Aggregation Reports",
    subtitle="Interactive visualizations generated from MongoDB Aggregation Pipelines and ML evaluation metrics",
    badge="Aggregation Framework",
)

db = get_db()
is_conn, _ = check_connection()

# Educational callout on MongoDB Aggregation Framework
st.markdown(
    """
    <div class="academic-box">
        <h4>🔬 CSE494 Concept: MongoDB Aggregation Pipelines</h4>
        <p>
            In Intelligent NoSQL Databases, analytics queries are executed through multi-stage aggregation pipelines.<br>
            • <code>$group</code>: Groups documents by specified keys (e.g. <code>$predicted_class</code>, <code>$model_name</code>) to compute accumulated totals (<code>$sum: 1</code>).<br>
            • <code>$project</code> & <code>$substrCP</code>: Transforms date strings into ISO day buckets for temporal analysis.<br>
            • <code>$sort</code>: Reorders grouped buckets in memory or via index without client-side recomputation.
        </p>
    </div>
    """,
    unsafe_allow_html=True,
)

# Important Distinction Disclaimer
st.info(
    "📌 **Methodological Distinction**: Model predictions shown below represent automated risk classifications "
    "generated by heuristic and statistical models. They should **never** be interpreted as verified fraud statistics. "
    "Ground-truth statistics refer strictly to validated historical records from the EMSCAD research dataset."
)

st.markdown("---")

# -------------------------------------------------------------
# 1. Prediction Analytics (MongoDB Predictions Collection)
# -------------------------------------------------------------
st.markdown("### 📊 1. Saved Predictions Analytics (predictions collection)")

# Fetch data via MongoDB Aggregation Pipelines
pred_dist = get_predictions_class_distribution(db=db) if is_conn else []
daily_trends = get_predictions_daily_trend(db=db) if is_conn else []
model_usage = get_model_usage_aggregation(db=db) if is_conn else []
feedback_data = get_feedback_breakdown(db=db) if is_conn else []

chart_col1, chart_col2 = st.columns(2)

with chart_col1:
    fig_pred_dist = create_prediction_distribution_chart(pred_dist)
    st.plotly_chart(fig_pred_dist, use_container_width=True)

with chart_col2:
    fig_trends = create_daily_trends_chart(daily_trends)
    st.plotly_chart(fig_trends, use_container_width=True)

chart_col3, chart_col4 = st.columns(2)

with chart_col3:
    fig_usage = create_model_usage_chart(model_usage)
    st.plotly_chart(fig_usage, use_container_width=True)

with chart_col4:
    fig_feedback = create_feedback_distribution_chart(feedback_data)
    st.plotly_chart(fig_feedback, use_container_width=True)

st.markdown("---")

# -------------------------------------------------------------
# 2. Ground Truth vs Model Evaluation
# -------------------------------------------------------------
st.markdown("### 🎯 2. Ground-Truth Data & Machine Learning Evaluation")

gt_data = get_jobs_ground_truth_distribution(db=db) if is_conn else []
metrics_meta = load_metrics_json() or {}

gt_col1, gt_col2 = st.columns(2)

with gt_col1:
    st.markdown("#### Dataset Class Distribution")
    fig_gt = create_ground_truth_distribution_chart(gt_data)
    st.plotly_chart(fig_gt, use_container_width=True)
    st.caption("Demonstrates the real-world ~4.8% minority class imbalance in the EMSCAD job postings corpus.")

with gt_col2:
    st.markdown("#### Model Performance Metrics Comparison")
    fig_comp = create_model_comparison_chart(metrics_meta)
    st.plotly_chart(fig_comp, use_container_width=True)
    st.caption("Comparison across Precision, Recall, F1-Score, and ROC-AUC on the held-out stratified test set.")
