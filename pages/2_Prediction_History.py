"""
Page C: Prediction History & Query Performance Analysis
ScamShield: AI-Powered Fake Job & Internship Detection System

Displays saved predictions retrieved from MongoDB Atlas with:
- Multi-parameter filtering (Class, Model, Keyword)
- explain() Query Execution Plan analysis (CSE494 syllabus concept)
- User feedback submission updating the feedback and predictions collections
"""

import streamlit as st
import pandas as pd
import config
from ui_utils import apply_custom_css, render_header, render_sidebar
from database.connection import get_db, check_connection
from database.operations import (
    get_saved_predictions,
    save_user_feedback,
    explain_query_plan,
)

st.set_page_config(
    page_title="Prediction History | ScamShield",
    page_icon="📋",
    layout="wide",
)

apply_custom_css()
render_sidebar()

render_header(
    title="Prediction History & Audit Log",
    subtitle="Query and audit previously evaluated recruitment listings from MongoDB Atlas",
    badge="PyMongo Find & Indexing",
)

db = get_db()
is_conn, _ = check_connection()

if not is_conn:
    st.warning("⚠️ MongoDB Atlas is not connected. Showing simulated offline view. Set `MONGODB_URI` in `.env` to query real database history.")

# 1. Filter and Search Controls
st.markdown("### 🔎 Query Filters")
f_col1, f_col2, f_col3, f_col4 = st.columns([2, 2, 2, 1])

with f_col1:
    class_filter = st.selectbox("Predicted Class", ["All", "Fraudulent", "Legitimate"])

with f_col2:
    model_filter = st.selectbox(
        "Model Architecture",
        ["All", "Logistic Regression (TF-IDF NLP)", "Random Forest (Structured Features)"],
    )

with f_col3:
    search_keyword = st.text_input("Search Job Title Keyword", placeholder="e.g. Engineer, Clerk...")

with f_col4:
    query_limit = st.selectbox("Result Limit", [10, 25, 50, 100], index=1)

# Construct MongoDB Query Dictionary
query_dict = {}
if class_filter != "All":
    query_dict["predicted_class"] = class_filter
if model_filter != "All":
    query_dict["model_name"] = model_filter
if search_keyword:
    query_dict["job_title"] = {"$regex": search_keyword, "$options": "i"}

# 2. Query Performance: explain() Demonstration (CSE494 Concept)
with st.expander("🔬 MongoDB Query Performance Analysis (explain())", expanded=False):
    st.markdown(
        """
        **CSE494 Topic: Indexing & Query Optimization**  
        In MongoDB, queries with matching B-Tree indexes perform an **Index Scan (`IXSCAN`)**, 
        while queries without indexes perform a **Collection Scan (`COLLSCAN`)**.  
        Below is the real execution plan generated by PyMongo's `.explain()` on this query:
        """
    )
    if is_conn:
        explain_info = explain_query_plan(
            collection_name=config.COLLECTION_PREDICTIONS,
            query=query_dict,
            sort=[("created_at", -1)],
            db=db,
        )
        e_col1, e_col2, e_col3 = st.columns(3)
        with e_col1:
            st.metric("Winning Plan Stage", explain_info.get("winning_plan_stage", "COLLSCAN"))
        with e_col2:
            st.metric("Index Applied", explain_info.get("index_used", "None"))
        with e_col3:
            st.metric("Execution Time (ms)", f"{explain_info.get('execution_time_ms', 0)} ms")

        st.caption(
            "Note: On small test datasets, `COLLSCAN` and `IXSCAN` may both complete in 0–1 ms. "
            "As document counts scale past hundreds of thousands of entries, compound indexes like "
            "`(predicted_class, created_at)` prevent expensive memory sorts and high disk I/O."
        )
    else:
        st.info("Connect to MongoDB Atlas to run live execution plan analysis via `explain()`.")

st.markdown("---")

# 3. Retrieve Records from MongoDB
predictions = []
if is_conn:
    predictions = get_saved_predictions(
        class_filter=class_filter if class_filter != "All" else None,
        model_filter=model_filter if model_filter != "All" else None,
        search_title=search_keyword,
        limit=query_limit,
        db=db,
    )

if not predictions:
    st.info("No prediction records found matching the current query criteria. Try adjusting your filters or run a scan on the Job Scam Detector page.")
else:
    st.markdown(f"**Found {len(predictions)} saved record(s)**:")

    # Table View
    table_data = []
    for p in predictions:
        table_data.append({
            "Prediction ID": p.get("prediction_id", "N/A"),
            "Title": p.get("job_title", "Untitled"),
            "Class": p.get("predicted_class", "Unknown"),
            "Confidence": f"{round(float(p.get('confidence', 0)) * 100, 1)}%",
            "Risk": p.get("risk_level", "Unknown"),
            "Model": p.get("model_name", "N/A"),
            "Feedback": p.get("feedback_status") or "None",
            "Created": str(p.get("created_at", ""))[:19].replace("T", " "),
        })

    df_display = pd.DataFrame(table_data)
    st.dataframe(df_display, use_container_width=True, hide_index=True)

    st.markdown("---")

    # 4. Detailed Inspection and Feedback Section
    st.markdown("### 🔍 Inspect Record & Submit User Feedback")
    pred_options = {p.get("prediction_id"): p for p in predictions}
    selected_id = st.selectbox(
        "Select a Prediction Record to Inspect:",
        options=list(pred_options.keys()),
        format_func=lambda x: f"{x} - {pred_options[x].get('job_title', 'Untitled')[:40]} ({pred_options[x].get('predicted_class')})",
    )

    if selected_id:
        doc = pred_options[selected_id]
        d_col1, d_col2 = st.columns([3, 2])

        with d_col1:
            st.markdown(f"#### Details for `{selected_id}`")
            st.markdown(f"**Job Title**: {doc.get('job_title')}")
            st.markdown(f"**Description Snippet**: {doc.get('job_description_snippet')}")
            st.markdown(f"**Predicted Class**: `{doc.get('predicted_class')}` | **Risk Level**: `{doc.get('risk_level')}`")
            st.markdown(f"**Confidence**: `{round(float(doc.get('confidence', 0)) * 100, 1)}%` | **Model**: `{doc.get('model_name')}`")

            # Indicators list
            inds = doc.get("detected_indicators", [])
            if inds:
                st.markdown("**Detected Heuristic Indicators**:")
                for i, ind in enumerate(inds, 1):
                    st.markdown(f"- **{ind.get('rule_name')}** ({ind.get('severity')}): {ind.get('description')}")
            else:
                st.caption("No suspicious indicators recorded for this listing.")

        with d_col2:
            st.markdown("#### 💬 Record User Feedback")
            st.caption("Audits prediction accuracy. Stored in MongoDB `feedback` collection.")

            feedback_val = st.radio(
                "Your Assessment of this Job Ad:",
                options=["Accurate", "Inaccurate", "Uncertain"],
                index=0,
                key=f"fb_{selected_id}",
            )
            feedback_notes = st.text_area(
                "Notes / Context (Optional)",
                placeholder="e.g. Confirmed company website has no record of this job posting...",
                key=f"notes_{selected_id}",
                height=80,
            )

            if st.button("Submit Feedback", type="primary"):
                if not is_conn:
                    st.error("Cannot save feedback: MongoDB Atlas is offline.")
                else:
                    success = save_user_feedback(
                        prediction_id=selected_id,
                        assessment=feedback_val,
                        notes=feedback_notes,
                        db=db,
                    )
                    if success:
                        st.success("✓ Feedback successfully saved to `feedback` collection and linked to prediction!")
                        st.rerun()
                    else:
                        st.error("Failed to save feedback to MongoDB.")

            st.caption(
                "Audit Note: User feedback is archived for evaluation and model monitoring. "
                "It is not treated as verified ground truth without independent manual corroboration."
            )
